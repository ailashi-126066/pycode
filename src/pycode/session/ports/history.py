"""Session navigation and lifetime around the append-only fact journal."""

from typing import Protocol

from pycode.kernel import EntryDraft, Message, SessionEntry, SessionSnapshot


class SessionStore(Protocol):
    async def append_message(self, message: Message) -> str: ...
    async def snapshot(self) -> SessionSnapshot: ...
    async def append_entry(self, draft: EntryDraft) -> SessionEntry: ...
    async def has_checkpoint(self, run_id: str) -> bool: ...
    async def checkpoint(self) -> object: ...
    async def branch(self, leaf_id: str | None) -> None: ...
    async def aclose(self) -> None: ...
