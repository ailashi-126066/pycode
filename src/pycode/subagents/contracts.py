"""What the subagent manager needs from the application; implemented in app/composition."""

from typing import Protocol

from pycode.kernel import EventConsumer, Message, RunResult
from pycode.subagents.types import Subagent, Worktree


class SubagentSession(Protocol):
    """One child AgentSession: its own history, checkpoint and runtime."""

    async def run(self, message: Message) -> RunResult: ...
    async def resume(self, answers: dict | None = None) -> RunResult: ...
    async def cancel(self) -> bool: ...
    async def aclose(self) -> None: ...


class SubagentSessions(Protocol):
    async def open(self, agent: Subagent, consumer: EventConsumer) -> SubagentSession: ...


class Worktrees(Protocol):
    async def create(self, agent_id: str) -> Worktree: ...
    async def changed(self, worktree: Worktree) -> bool: ...
    async def remove(self, worktree: Worktree) -> None: ...
    async def commit(self, worktree: Worktree, message: str) -> None: ...
